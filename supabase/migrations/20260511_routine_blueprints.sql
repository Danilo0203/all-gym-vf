-- backfill: create a blueprint from every active/draft routine
do $$
declare
  r record;
  bp_id uuid;
begin
  for r in
    select *
    from public.routines
    where status in ('active', 'draft')
      and user_id is not null
  loop
    insert into public.routine_blueprints (
      id, name, primary_goal, secondary_goal,
      source_routine_id, created_by, created_at, updated_at
    ) values (
      gen_random_uuid(),
      coalesce(r.name, 'Rutina'),
      r.primary_goal,
      r.secondary_goal,
      r.id,
      coalesce(r.created_by, r.user_id),
      coalesce(r.reviewed_at, now()),
      coalesce(r.reviewed_at, now())
    )
    returning id into bp_id;

    insert into public.routine_blueprint_details (
      blueprint_id, day_of_week, exercise_id, exercise_order,
      block_type, sets, reps, rest_seconds, duration_minutes,
      target_rir, notes, exercise_name_snapshot
    )
    select
      bp_id, rd.day_of_week, rd.exercise_id, rd.exercise_order,
      rd.block_type, rd.sets, rd.reps, rd.rest_seconds,
      rd.duration_minutes, rd.target_rir, rd.notes,
      rd.exercise_name_snapshot
    from public.routine_details rd
    where rd.routine_id = r.id
    order by rd.day_of_week, rd.exercise_order;

    insert into public.routine_blueprint_assignments (
      id, blueprint_id, user_id, assigned_routine_id, assigned_by, assigned_at
    ) values (
      gen_random_uuid(),
      bp_id,
      r.user_id,
      r.id,
      coalesce(r.created_by, r.user_id),
      coalesce(r.reviewed_at, now())
    );
  end loop;
end $$;
